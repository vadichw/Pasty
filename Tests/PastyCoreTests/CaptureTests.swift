import AppKit
import Testing
@testable import PastyCore

extension UsesPrefs {
    @MainActor
    struct CaptureTests {
        let store = makeStore()
        let pasteboard = scratchPasteboard()
        let monitor: ClipboardMonitor

        init() {
            useScratchDefaults()
            monitor = ClipboardMonitor(store: store, pasteboard: pasteboard)
        }

        private func copy(_ text: String, extra: [String: Data] = [:]) {
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            for (type, data) in extra { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
            pasteboard.clearContents()
            pasteboard.writeObjects([item])
        }

        @Test("INV-Capture-1: content marked concealed or transient is never recorded", arguments: [
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        ])
        func markedContentIgnored(marker: String) {
            copy("secret", extra: [marker: Data()])
            monitor.check()
            #expect(store.items.isEmpty)
        }

        @Test("INV-Capture-2: nothing is recorded while paused, not even after resuming")
        func pause() {
            Prefs.paused = true
            copy("while paused")
            monitor.check()
            Prefs.paused = false
            monitor.check()
            #expect(store.items.isEmpty)

            copy("after")
            monitor.check()
            #expect(store.items.map(\.text) == ["after"])
        }

        @Test("INV-Capture-3: a change made before skipCurrentChange() is not recorded")
        func skipCurrentChange() {
            copy("written by Pasty")
            monitor.skipCurrentChange()
            monitor.check()
            #expect(store.items.isEmpty)
        }

        @Test("INV-Capture-4: one media file → image/video with filePath; several files → files; text → text; image data → image")
        func classification() throws {
            let folder = temporaryDirectory()
            let image = folder.appendingPathComponent("photo.png")
            try pngData(width: 8, height: 6).write(to: image)
            let video = folder.appendingPathComponent("clip.mov")
            try Data().write(to: video)
            let notes = folder.appendingPathComponent("notes.txt")
            let other = folder.appendingPathComponent("other.txt")

            monitor.record(contents: [[:]], fileURLs: [image], string: nil, imageData: nil, appBundleID: nil)
            monitor.record(contents: [[:]], fileURLs: [video], string: nil, imageData: nil, appBundleID: nil)
            monitor.record(contents: [[:]], fileURLs: [notes, other], string: nil, imageData: nil, appBundleID: nil)
            monitor.record(contents: [[:]], fileURLs: [], string: "hello", imageData: nil, appBundleID: nil)
            monitor.record(contents: [[:]], fileURLs: [], string: nil, imageData: pngData(width: 3, height: 2), appBundleID: nil)

            let byKind = Dictionary(grouping: store.items, by: \.kind)
            #expect(byKind[.image]?.contains { $0.filePath == image.path && $0.text == "photo.png — 8×6" } == true)
            #expect(byKind[.video]?.first?.filePath == video.path)
            #expect(byKind[.files]?.first?.text == notes.path + "\n" + other.path)
            #expect(byKind[.text]?.first?.text == "hello")
            #expect(byKind[.image]?.contains { $0.filePath == nil && $0.text == "Image 3×2" } == true)
        }

        @Test("INV-Capture-5: content over 50 MB is not recorded")
        func sizeLimit() {
            copy("big", extra: ["com.example.big": Data(count: 51 * 1024 * 1024)])
            monitor.check()
            #expect(store.items.isEmpty)
        }

        @Test("INV-Capture-6: text items keep 2000 characters for search but the full text in contents")
        func longText() {
            let long = String(repeating: "abcdefghij", count: 500)
            copy(long)
            monitor.check()
            let item = try! #require(store.items.first)
            #expect(item.text.count == 2000)
            let stored = store.contents(for: item)?.first?[plainTextType].flatMap { String(data: $0, encoding: .utf8) }
            #expect(stored == long)
        }

        @Test("INV-Capture-7: existing files are ignored; a new file is reported once, after its size settles")
        func screenshotWatcher() throws {
            let folder = temporaryDirectory()
            try pngData(width: 2, height: 2).write(to: folder.appendingPathComponent("existing.png"))
            Prefs.screenshotFolder = folder.path
            let watcher = ScreenshotWatcher()
            var reported: [String] = []
            watcher.onCapture = { reported.append($0.lastPathComponent) }
            watcher.restart()
            defer { watcher.stop() }

            try pngData(width: 2, height: 2).write(to: folder.appendingPathComponent("new.png"))
            try Data().write(to: folder.appendingPathComponent("empty.png"))
            watcher.scan()
            watcher.checkPending()
            #expect(reported.isEmpty) // first look: size not known to be stable yet
            watcher.checkPending()
            #expect(reported == ["new.png"])

            watcher.scan()
            watcher.checkPending()
            watcher.checkPending()
            #expect(reported == ["new.png"]) // not again, and never the empty or existing file
        }

        @Test("INV-Capture-8: durations round to whole seconds, m:ss or h:mm:ss")
        func durations() {
            #expect(MediaFile.formatDuration(5) == "0:05")
            #expect(MediaFile.formatDuration(65.4) == "1:05")
            #expect(MediaFile.formatDuration(3725) == "1:02:05")
        }

        @Test("INV-Capture-9: with Save images off, image data alone is not recorded")
        func saveImagesOff() {
            Prefs.defaults.set(false, forKey: Prefs.Key.saveImages)
            monitor.record(contents: [[:]], fileURLs: [], string: nil, imageData: pngData(width: 3, height: 2), appBundleID: nil)
            #expect(store.items.isEmpty)
        }
    }
}
