import AppKit

/// Polls `NSPasteboard.general.changeCount` (macOS has no change notification) and
/// records new contents into the history store.
@MainActor
final class ClipboardMonitor {
    private let pasteboard = NSPasteboard.general
    private let store: HistoryStore
    private var lastChangeCount: Int
    private var timer: Timer?

    private static let maxItemSize = 50 * 1024 * 1024

    /// Markers used by password managers and utilities for data that shouldn't be kept
    /// (see nspasteboard.org).
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    private static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff]

    init(store: HistoryStore) {
        self.store = store
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        // Lets macOS batch our wakeups with other timers to save energy.
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Call after writing to the pasteboard ourselves so the change isn't re-recorded.
    func skipCurrentChange() {
        lastChangeCount = pasteboard.changeCount
    }

    private func check() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard !Prefs.paused else { return }
        // Drain pasteboard buffers right away instead of at the end of the run loop pass.
        autoreleasepool { capture() }
    }

    private func capture() {
        guard let pasteboardItems = pasteboard.pasteboardItems, !pasteboardItems.isEmpty else { return }

        let allTypes = Set(pasteboardItems.flatMap { $0.types.map(\.rawValue) })
        guard allTypes.isDisjoint(with: Self.ignoredTypes) else { return }

        let appBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let appBundleID, Prefs.ignoredApps.contains(appBundleID) { return }

        var contents: ClipContents = []
        var totalSize = 0
        for item in pasteboardItems {
            var dict: [String: Data] = [:]
            for type in item.types where !type.rawValue.hasPrefix("dyn.") {
                guard let data = item.data(forType: type) else { continue }
                dict[type.rawValue] = data
                totalSize += data.count
            }
            if !dict.isEmpty { contents.append(dict) }
        }
        guard !contents.isEmpty, totalSize <= Self.maxItemSize else { return }

        let fileURLs = pasteboard.readObjects(
            forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]
        ) as? [URL] ?? []
        // Reuse the bytes already read above rather than asking the pasteboard again.
        let first = contents.first ?? [:]
        let imageData = Self.imageTypes.lazy.compactMap { first[$0.rawValue] }.first
        let string = first[NSPasteboard.PasteboardType.string.rawValue].flatMap { String(data: $0, encoding: .utf8) }
            ?? pasteboard.string(forType: .string)

        record(contents: contents, fileURLs: fileURLs, string: string,
               imageData: imageData, appBundleID: appBundleID)
    }

    /// Classifies captured data and adds it to the history.
    /// Also used for screenshots and screen recordings picked up from disk.
    func record(contents: ClipContents, fileURLs: [URL], string: String?, imageData: Data?, appBundleID: String?) {
        if fileURLs.count == 1, let url = fileURLs.first, let media = MediaFile.kind(of: url) {
            recordMediaFile(url, kind: media, contents: contents, appBundleID: appBundleID)
        } else if !fileURLs.isEmpty {
            let text = fileURLs.map(\.path).joined(separator: "\n")
            store.add(kind: .files, text: text, hash: HistoryStore.hash("files:" + text),
                      contents: contents, appBundleID: appBundleID, thumbnail: nil)
        } else if let string, !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            store.add(kind: .text, text: String(string.prefix(ClipItem.searchTextLimit)),
                      hash: HistoryStore.hash("text:" + string),
                      contents: contents, appBundleID: appBundleID, thumbnail: nil)
        } else if Prefs.saveImages, let imageData, let info = MediaFile.imageInfo(data: imageData) {
            store.add(kind: .image, text: "Image \(info.width)×\(info.height)",
                      hash: HistoryStore.hash(imageData),
                      contents: contents, appBundleID: appBundleID, thumbnail: info.thumbnail)
        }
    }

    private func recordMediaFile(_ url: URL, kind: MediaFile.Kind, contents: ClipContents, appBundleID: String?) {
        let name = url.lastPathComponent
        let hash = HistoryStore.hash("file:" + url.path)
        switch kind {
        case .image:
            let info = MediaFile.imageInfo(url: url)
            let size = info.map { " — \($0.width)×\($0.height)" } ?? ""
            store.add(kind: .image, text: name + size, hash: hash, contents: contents,
                      appBundleID: appBundleID, thumbnail: info?.thumbnail, filePath: url.path)
        case .video:
            let id = store.add(kind: .video, text: name, hash: hash, contents: contents,
                               appBundleID: appBundleID, thumbnail: nil, filePath: url.path)
            Task { [store] in
                let info = await MediaFile.videoInfo(url: url)
                let text = info.duration.map { "\(name) — \(MediaFile.formatDuration($0))" }
                store.updateMedia(id: id, thumbnail: info.thumbnail, text: text)
            }
        }
    }
}
